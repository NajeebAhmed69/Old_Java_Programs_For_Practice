package UniPractise;

public class AssignmentOperators {
    public static void main(String [] args){

        int x = 90;
        x = 10;
        System.out.println(x);

        int y = 30;
        y *= 2;
        System.out.println(y);

        int z = 5;
        z /= 2;
        System.out.println(z);

        for(int i = 1; i<=10; i +=1){
            System.out.println(i);
        }


    }
}
